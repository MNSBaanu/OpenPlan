// Writes public/third-party-notices.txt: the licenses of the libraries and the font that are shipped with OpenPlan.
// Run `npm run notices` after changing dependencies. `npm run notices -- --check` only checks that the file is current.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'public', 'third-party-notices.txt');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

// Every package that ends up in the app: the production dependencies and what they depend on.
const found = new Map();
const find = (name, from) => {
  for (let d = from; ; d = dirname(d)) {
    const p = join(d, 'node_modules', name);
    if (existsSync(join(p, 'package.json'))) return p;
    if (dirname(d) === d) return null;
  }
};
const visit = (name, from) => {
  const dir = find(name, from);
  if (!dir || found.has(dir)) return;
  const j = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  found.set(dir, j);
  Object.keys(j.dependencies || {}).forEach(n => visit(n, dir));
};
Object.keys(pkg.dependencies || {}).forEach(n => visit(n, root));

const licenseText = dir => {
  const f = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE'].map(n => join(dir, n)).find(existsSync);
  return f ? readFileSync(f, 'utf8').trim() : null;
};

const rule = '='.repeat(78);
const parts = [
  'OpenPlan: notices for software and fonts shipped with it',
  '',
  'OpenPlan itself is released under the MIT License (see LICENSE in the repository).',
  'It includes the following third-party software and fonts, each under its own license.',
  'This file is generated by scripts/make-notices.mjs.',
  ''
];
const sorted = [...found.entries()].sort((a, b) => a[1].name.localeCompare(b[1].name));
const missing = [];
for (const [dir, j] of sorted) {
  const text = licenseText(dir);
  if (!text) missing.push(j.name);
  parts.push(rule, j.name + ' ' + j.version + '  (' + (typeof j.license === 'string' ? j.license : 'see below') + ')', j.homepage || (j.repository && (j.repository.url || j.repository)) || '', rule, '', text || '(No license file is included in the package. License: ' + j.license + ')', '');
}
// The visit counter is copied into the project rather than installed, so it is listed by hand.
const counter = readFileSync(join(root, 'public', 'count.js'), 'utf8');
if (/ISC license/.test(counter)) {
  parts.push(rule, 'GoatCounter count.js  (ISC)', 'https://www.goatcounter.com', rule, '', 'public/count.js is released under the ISC license: https://opensource.org/licenses/ISC', '');
}
const text = parts.join('\n').replace(/\r\n/g, '\n').replace(/\n{4,}/g, '\n\n\n');

if (process.argv.includes('--check')) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have !== text) { console.error('public/third-party-notices.txt is out of date. Run: npm run notices'); process.exit(1); }
  console.log('Notices are up to date (' + found.size + ' packages).');
} else {
  writeFileSync(OUT, text);
  console.log('Wrote ' + OUT + ' (' + found.size + ' packages)' + (missing.length ? '. No license file in: ' + missing.join(', ') : ''));
}
